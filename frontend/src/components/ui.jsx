import { ALERT_STATUS_META, SEVERITY_META, STATUS_META } from "../utils/constants.js";
import { relativeTime } from "../utils/format.js";
import Icon from "./Icon.jsx";

export function Badge({ children, color = "#334155", bg = "#e2e8f0", title }) {
  return (
    <span className="badge" style={{ color, background: bg }} title={title}>
      {children}
    </span>
  );
}

export function StatusBadge({ status }) {
  const m = STATUS_META[status] || STATUS_META.no_data;
  return (
    <span className="badge" style={{ color: m.color, background: m.bg }}>
      <span className="dot" style={{ background: m.color }} />
      {m.label}
    </span>
  );
}

export const SeverityBadge = ({ severity }) => {
  const m = SEVERITY_META[severity] || SEVERITY_META.info;
  return <Badge color={m.color} bg={m.bg}>{m.label}</Badge>;
};

export const AlertStatusBadge = ({ status }) => {
  const m = ALERT_STATUS_META[status] || ALERT_STATUS_META.active;
  return <Badge color={m.color} bg={m.bg}>{m.label}</Badge>;
};

export function SimulatedTag({ simulated = true }) {
  return simulated ? (
    <Badge color="#7c3aed" bg="#ede9fe" title="Generated by the built-in simulator, not a real sensor">SIMULATED</Badge>
  ) : (
    <Badge color="#0f766e" bg="#ccfbf1" title="Received from real hardware">HARDWARE</Badge>
  );
}

export function Card({ title, actions, children, className = "", padded = true }) {
  return (
    <section className={`card ${className}`}>
      {(title || actions) && (
        <header className="card-header">
          <h3 className="card-title">{title}</h3>
          <div className="row">{actions}</div>
        </header>
      )}
      <div className={padded ? "card-body" : ""}>{children}</div>
    </section>
  );
}

export function StatCard({ label, value, hint, tone }) {
  return (
    <div className={`stat-card ${tone ? `tone-${tone}` : ""}`}>
      <div className="stat-label">{label}</div>
      <div className="stat-value">{value}</div>
      {hint && <div className="stat-hint">{hint}</div>}
    </div>
  );
}

export function PageHeader({ title, subtitle, actions }) {
  return (
    <div className="page-header">
      <div>
        <h1>{title}</h1>
        {subtitle && <p className="muted">{subtitle}</p>}
      </div>
      <div className="row">{actions}</div>
    </div>
  );
}

export const Loading = ({ text = "Loading…" }) => (
  <div className="loading"><span className="spinner" /> {text}</div>
);

export function ErrorBox({ error, onRetry }) {
  return (
    <div className="error-box" role="alert">
      <strong>Something went wrong.</strong>
      <div>{error?.message || "Unknown error"}</div>
      {onRetry && <button className="btn btn-sm" onClick={onRetry}>Try again</button>}
    </div>
  );
}

export const EmptyState = ({ children }) => <div className="empty">{children}</div>;

/** Handles the loading / error states of a useApi() result. children(data) renders the loaded UI. */
export function DataState({ result, children, loadingText }) {
  if (result.loading && !result.data) return <Loading text={loadingText} />;
  if (result.error && !result.data) return <ErrorBox error={result.error} onRetry={result.reload} />;
  if (!result.data) return null;
  return (
    <>
      {result.error && <div className="stale-note">Could not refresh: {result.error.message}. Showing the last data received.</div>}
      {children(result.data)}
    </>
  );
}

export function LiveIndicator({ updatedAt, loading }) {
  return (
    <span className="live" title="Data refreshes automatically">
      <span className={`live-dot ${loading ? "pulse" : ""}`} />
      {updatedAt ? `Updated ${relativeTime(updatedAt.toISOString())}` : "Waiting for data…"}
    </span>
  );
}

export function OccupancyBar({ value, capacity, mode }) {
  if (value === null || value === undefined) return <span className="muted">no data</span>;
  if (mode === "presence") return <span>{value ? "Presence detected" : "No presence"}</span>;
  const pct = capacity ? Math.min(100, Math.round((100 * value) / capacity)) : 0;
  const over = capacity && value > capacity;
  return (
    <div className="occ">
      <div className="progress"><div className={`progress-bar ${over ? "over" : ""}`} style={{ width: `${pct}%` }} /></div>
      <span className="occ-text">{value}/{capacity}</span>
    </div>
  );
}

export function Tabs({ tabs, value, onChange }) {
  return (
    <div className="tabs" role="tablist">
      {tabs.map((t) => (
        <button key={t.value} role="tab" aria-selected={value === t.value} className={`tab ${value === t.value ? "active" : ""}`} onClick={() => onChange(t.value)}>
          {t.label}
        </button>
      ))}
    </div>
  );
}

export const RefreshButton = ({ onClick }) => (
  <button className="btn btn-sm btn-ghost" onClick={onClick} title="Refresh now"><Icon name="refresh" size={14} /> Refresh</button>
);
