import { useEffect, useRef, useState } from "react";
import { NavLink, Outlet, useLocation, useNavigate } from "react-router-dom";
import { api } from "../api/client.js";
import { MetaContext } from "../context/MetaContext.jsx";
import { useAuth } from "../context/AuthContext.jsx";
import { useApi } from "../hooks/useApi.js";
import { NAV_ITEMS, ROLE_LABELS, SEVERITY_META } from "../utils/constants.js";
import { alertLocation, relativeTime, twinLink } from "../utils/format.js";
import Icon from "./Icon.jsx";
import Logo from "./Logo.jsx";

function DataBanner({ meta }) {
  if (!meta) return null;
  let text = null;
  if (meta.data_source === "simulated") {
    text = "SIMULATED DATA: sensor values are generated by the built-in simulator, not by real IoT devices.";
  } else if (meta.data_source === "mixed") {
    text = "MIXED DATA: some devices are real ESP32 hardware, the others are simulated (see IoT Devices).";
  }
  const sample = meta.campus_data_is_sample ? " Campus layout and timetable are sample data." : "";
  if (!text && !sample) return null;
  return (
    <div className="banner" role="status">
      <strong>{text || "Hardware data."}</strong>
      {sample}
    </div>
  );
}

function useOutsideClick(ref, handler) {
  useEffect(() => {
    const listener = (e) => {
      if (ref.current && !ref.current.contains(e.target)) handler();
    };
    document.addEventListener("mousedown", listener);
    return () => document.removeEventListener("mousedown", listener);
  }, [ref, handler]);
}

function GlobalSearch() {
  const [q, setQ] = useState("");
  const [results, setResults] = useState([]);
  const [open, setOpen] = useState(false);
  const [message, setMessage] = useState("");
  const ref = useRef(null);
  const navigate = useNavigate();
  useOutsideClick(ref, () => setOpen(false));

  useEffect(() => {
    if (q.trim().length < 2) {
      setResults([]);
      setMessage("");
      return undefined;
    }
    let cancelled = false;
    const timer = setTimeout(async () => {
      try {
        const data = await api.search(q.trim());
        if (!cancelled) {
          setResults(data);
          setMessage(data.length ? "" : "No results");
        }
      } catch (e) {
        if (!cancelled) setMessage(e.message);
      }
    }, 250);
    return () => {
      cancelled = true;
      clearTimeout(timer);
    };
  }, [q]);

  const choose = (r) => {
    setOpen(false);
    setQ("");
    if (r.type === "building") navigate(twinLink({ building_id: r.building_id }));
    else if (r.type === "room") navigate(twinLink({ building_id: r.building_id, floor_id: r.floor_id, room_id: r.room_id }));
    else if (r.type === "device") navigate(`/devices?device=${r.id}`);
    else if (r.type === "alert") navigate(`/incidents?highlight=${r.id}`);
  };

  return (
    <div className="search-box" ref={ref}>
      <Icon name="search" size={16} />
      <input value={q} placeholder="Search buildings, rooms, devices, incidents…" onChange={(e) => { setQ(e.target.value); setOpen(true); }} onFocus={() => setOpen(true)} aria-label="Global search" />
      {open && (results.length > 0 || message) && (
        <div className="dropdown search-results">
          {message && <div className="dropdown-note">{message}</div>}
          {results.map((r) => (
            <button key={`${r.type}-${r.id}`} className="dropdown-item" onClick={() => choose(r)}>
              <span className="result-type">{r.type}</span>
              <span>
                <div>{r.label}</div>
                <div className="muted small">{r.sublabel}</div>
              </span>
            </button>
          ))}
        </div>
      )}
    </div>
  );
}

function NotificationBell() {
  const { user } = useAuth();
  const navigate = useNavigate();
  const [open, setOpen] = useState(false);
  const ref = useRef(null);
  useOutsideClick(ref, () => setOpen(false));
  const { data } = useApi(() => api.alerts({ status: "active", limit: 8 }), [], { interval: 8000 });
  const alerts = data || [];

  const openAlert = (a) => {
    setOpen(false);
    if (user.role === "student") navigate(twinLink({ building_id: a.building_id, floor_id: a.floor_id, room_id: a.room_id, id: a.id }));
    else navigate(`/incidents?highlight=${a.id}`);
  };

  return (
    <div className="bell-wrap" ref={ref}>
      <button className="icon-btn" onClick={() => setOpen((o) => !o)} aria-label="Notifications">
        <Icon name="bell" />
        {alerts.length > 0 && <span className="bell-badge">{alerts.length}</span>}
      </button>
      {open && (
        <div className="dropdown notif">
          <div className="dropdown-title">Active alerts</div>
          {alerts.length === 0 && <div className="dropdown-note">No active alerts.</div>}
          {alerts.map((a) => (
            <button key={a.id} className="dropdown-item" onClick={() => openAlert(a)}>
              <span className="sev-dot" style={{ background: SEVERITY_META[a.severity]?.color }} />
              <span>
                <div>{a.message}</div>
                <div className="muted small">{alertLocation(a)} · {relativeTime(a.created_at)}</div>
              </span>
            </button>
          ))}
        </div>
      )}
    </div>
  );
}

export default function Layout() {
  const { user, logout } = useAuth();
  const navigate = useNavigate();
  const location = useLocation();
  const [menuOpen, setMenuOpen] = useState(false);
  const meta = useApi(() => api.meta(), [], { interval: 30000 });
  const items = NAV_ITEMS.filter((i) => i.roles.includes(user.role));

  useEffect(() => setMenuOpen(false), [location.pathname]);

  const handleLogout = () => {
    logout();
    navigate("/login");
  };

  return (
    <MetaContext.Provider value={meta.data}>
      <div className="app-shell">
        <aside className={`sidebar ${menuOpen ? "open" : ""}`}>
          <div className="brand">
            <Logo size={38} />
            <div>
              <div className="brand-title">ASIET</div>
              <div className="brand-sub">Campus Digital Twin</div>
            </div>
          </div>
          <nav>
            {items.map((item) => (
              <NavLink key={item.path} to={item.path} end={item.end} className={({ isActive }) => `nav-link ${isActive ? "active" : ""}`}>
                <Icon name={item.icon} />
                <span>{item.labels?.[user.role] || item.label}</span>
              </NavLink>
            ))}
          </nav>
          <div className="sidebar-foot">Digital Operations Centre<br />Final-year project prototype</div>
        </aside>
        {menuOpen && <div className="scrim" onClick={() => setMenuOpen(false)} />}

        <div className="main">
          <header className="topbar">
            <button className="icon-btn menu-btn" onClick={() => setMenuOpen((o) => !o)} aria-label="Menu"><Icon name="menu" /></button>
            <GlobalSearch />
            <div className="spacer" />
            <NotificationBell />
            <div className="user-chip">
              <div className="avatar">{user.name.charAt(0)}</div>
              <div className="user-meta">
                <div>{user.name}</div>
                <div className="muted small">{ROLE_LABELS[user.role]}</div>
              </div>
            </div>
            <button className="btn btn-sm btn-ghost" onClick={handleLogout}><Icon name="logout" size={15} /> Logout</button>
          </header>
          <DataBanner meta={meta.data} />
          <main className="content">
            <Outlet />
          </main>
        </div>
      </div>
    </MetaContext.Provider>
  );
}
